import 'package:shared_preferences/shared_preferences.dart';

/// How the tablet reaches Home Assistant. Like the companion app it has an internal address (used at home) and an
/// optional external one (used elsewhere); [policy] can restrict the persistent connection to the home network.
class ConnectionSettings {
  const ConnectionSettings({
    this.haUrl = '',
    this.token = '',
    this.externalUrl = '',
    this.homeSsids = const [],
    this.vpnIsHome = false,
    this.ethernetIsHome = true,
    this.policy = ConnectionPolicy.always,
  });

  /// Internal address (used at home, and whenever there is no better information).
  final String haUrl;

  /// Per-device pairing token generated by the HA integration.
  final String token;

  /// Address reachable from outside; empty = none, the internal one is used everywhere.
  final String externalUrl;

  /// Wi-Fi names that count as "home".
  final List<String> homeSsids;

  /// A connected VPN counts as home (HA is reachable through it on its internal address).
  final bool vpnIsHome;

  /// A wired connection counts as home.
  final bool ethernetIsHome;
  final ConnectionPolicy policy;

  bool get isPaired => haUrl.isNotEmpty && token.isNotEmpty;

  ConnectionSettings copyWith({
    String? haUrl,
    String? token,
    String? externalUrl,
    List<String>? homeSsids,
    bool? vpnIsHome,
    bool? ethernetIsHome,
    ConnectionPolicy? policy,
  }) => ConnectionSettings(
    haUrl: haUrl ?? this.haUrl,
    token: token ?? this.token,
    externalUrl: externalUrl ?? this.externalUrl,
    homeSsids: homeSsids ?? this.homeSsids,
    vpnIsHome: vpnIsHome ?? this.vpnIsHome,
    ethernetIsHome: ethernetIsHome ?? this.ethernetIsHome,
    policy: policy ?? this.policy,
  );

  /// `http://ha.local:8123` -> `ws://ha.local:8123/api/ha_sidecar/ws`
  Uri get websocketUri => websocketUriFor(haUrl);

  static Uri websocketUriFor(String url) {
    final base = Uri.parse(url.trim());
    final secure = base.scheme == 'https' || base.scheme == 'wss';
    final prefix = base.path.endsWith('/')
        ? base.path.substring(0, base.path.length - 1)
        : base.path;
    return base.replace(
      scheme: secure ? 'wss' : 'ws',
      path: '$prefix/api/ha_sidecar/ws',
    );
  }

  static Future<ConnectionSettings> load() async {
    final p = await SharedPreferences.getInstance();
    return ConnectionSettings(
      haUrl: p.getString('ha_url') ?? '',
      token: p.getString('token') ?? '',
      externalUrl: p.getString('external_url') ?? '',
      homeSsids: p.getStringList('home_ssids') ?? const [],
      vpnIsHome: p.getBool('vpn_is_home') ?? false,
      ethernetIsHome: p.getBool('ethernet_is_home') ?? true,
      policy: p.getString('connection_policy') == 'home_only'
          ? ConnectionPolicy.homeOnly
          : ConnectionPolicy.always,
    );
  }

  Future<void> save() async {
    final p = await SharedPreferences.getInstance();
    await p.setString('ha_url', haUrl.trim());
    await p.setString('token', token.trim());
    await p.setString('external_url', externalUrl.trim());
    await p.setStringList('home_ssids', homeSsids);
    await p.setBool('vpn_is_home', vpnIsHome);
    await p.setBool('ethernet_is_home', ethernetIsHome);
    await p.setString(
      'connection_policy',
      policy == ConnectionPolicy.homeOnly ? 'home_only' : 'always',
    );
  }

  static Future<void> clear() async {
    final p = await SharedPreferences.getInstance();
    for (final k in ['ha_url', 'token', 'external_url']) {
      await p.remove(k);
    }
  }
}

/// `always`: stay connected on any network (internal address at home, external elsewhere).
/// `homeOnly`: keep the persistent connection only while on a home network (or home VPN / Ethernet).
enum ConnectionPolicy { always, homeOnly }
